#!/usr/bin/env python3
"""run_findings.py - what the parallel run teaches (T-020). Read-only, stdlib only.

Reads plan/telemetry/runs.jsonl + events.jsonl and the router file usage-72h.json,
prints (and with --out writes) a markdown SUMMARY: real provider/model per run,
busy hits and agents in flight. Bad lines are skipped and counted.

Usage: python3 tools/run_findings.py [--telemetry DIR] [--router-home DIR] [--out FILE]
"""
import argparse
import calendar
import json
import os
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path

NOT_A_MODEL = {"", "unknown", "general-purpose", "haiku", "sonnet", "opus", "none", "nan"}


def load_jsonl(path):
    rows, bad = [], 0
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return rows, bad
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
            if isinstance(obj, dict):
                rows.append(obj)
            else:
                bad += 1
        except ValueError:
            bad += 1
    return rows, bad


def load_json(path):
    try:
        obj = json.loads(Path(path).read_text(encoding="utf-8"))
        return obj if isinstance(obj, dict) else {}
    except (OSError, ValueError):
        return {}


def parse_ts(s):
    """ISO string -> epoch seconds, or None."""
    if not isinstance(s, str):
        return None
    s = s.strip().replace("Z", "")
    if "." in s:
        s = s.split(".")[0]
    try:
        return calendar.timegm(time.strptime(s[:19], "%Y-%m-%dT%H:%M:%S"))
    except ValueError:
        return None


def router_models(usage, t0, t1):
    """Provider/model pairs the router counted in the hours [t0, t1] (usage-72h.json format)."""
    h0, h1 = int(t0 // 3600), int(t1 // 3600)
    found = []
    for e in usage.values():
        if not isinstance(e, dict):
            continue
        hours = e.get("hours", {})
        if any(x.lstrip("-").isdigit() and h0 <= int(x) <= h1 and (v[2] if len(v) > 2 else 0) for x, v in hours.items()):
            found.append("%s/%s" % (e.get("provider", "?"), e.get("model", "?")))
    return sorted(found)


def real_model(run, usage):
    """(models list, source). Never an agent type or Claude alias."""
    m = run.get("models")
    if isinstance(m, list) and m:
        return [str(x) for x in m], run.get("model_source", "run")
    v = str(run.get("model", "")).strip()
    if v.lower() not in NOT_A_MODEL:
        return [v], run.get("model_source", "run")
    t0 = parse_ts(run.get("ts_start") or run.get("started"))
    t1 = parse_ts(run.get("ts_end") or run.get("ended")) or t0
    if t0 is not None:
        found = router_models(usage, t0, t1)
        if found:
            return found, "router-log"
    return ["unknown"], "none"


def build(telemetry, router_home):
    runs, bad_r = load_jsonl(Path(telemetry) / "runs.jsonl")
    events, bad_e = load_jsonl(Path(telemetry) / "events.jsonl")
    usage = load_json(Path(router_home) / "usage-72h.json") if router_home else {}
    per = defaultdict(lambda: Counter())
    rows = []
    for r in runs:
        models, src = real_model(r, usage)
        key = "+".join(models)
        out = str(r.get("outcome", "?"))
        per[key]["runs"] += 1
        per[key][out] += 1
        rows.append((str(r.get("cmd", "?")), str(r.get("area", "")), key, src, out))
    busy_runs = sum(1 for r in runs if r.get("outcome") == "busy")
    busy_ev = [e for e in events if e.get("event") == "limit_busy"]
    busy_hits = busy_runs + sum(int(e.get("count", 1) or 1) for e in busy_ev)
    flights = [(e.get("ts", "?"), int(e["agents_in_flight"])) for e in events
               if isinstance(e.get("agents_in_flight"), (int, float))]
    maxpar = max((int(e.get("max_parallel", 0) or 0) for e in events), default=0)

    L = ["# Run findings (generated by tools/run_findings.py)", ""]
    L.append("Sources: %d runs, %d events, router usage entries: %d. Skipped bad lines: %d." % (len(runs), len(events), len(usage), bad_r + bad_e))
    L += ["", "## 1. Real provider/model per model", "", "| Provider/model | Runs | Done | Busy | Other |", "|---|---|---|---|---|"]
    for k, c in sorted(per.items(), key=lambda x: -x[1]["runs"]):
        other = c["runs"] - c["done"] - c["busy"]
        L.append("| %s | %d | %d | %d | %d |" % (k, c["runs"], c["done"], c["busy"], other))
    L += ["", "## 2. Per run", "", "| Cmd | Area | Provider/model | Model source | Outcome |", "|---|---|---|---|---|"]
    for cmd, area, key, src, out in rows:
        L.append("| %s | %s | %s | %s | %s |" % (cmd, area, key, src, out))
    unk = sum(1 for x in rows if x[2] == "unknown")
    L += ["", "## 3. Busy hits", "", "- Runs with outcome busy: %d" % busy_runs,
          "- limit_busy events: %d (counted hits: %d)" % (len(busy_ev), busy_hits - busy_runs)]
    for e in busy_ev:
        L.append("  - %s: %s" % (e.get("ts", "?"), str(e.get("note") or e.get("detail") or "")[:120]))
    L += ["", "## 4. Agents in flight", ""]
    if flights:
        L.append("- Peak agents in flight: %d (max_parallel seen: %d)" % (max(v for _, v in flights), maxpar))
        for ts, v in flights:
            L.append("  - %s: %d" % (ts, v))
    else:
        L.append("- No agents_in_flight data in events.")
    L += ["", "Runs with unknown model: %d of %d (no router record for the window)." % (unk, len(rows))]
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--telemetry", default=str(Path(__file__).resolve().parent.parent / "plan" / "telemetry"))
    ap.add_argument("--router-home", default=os.environ.get("DREAM_ROUTER_HOME") or os.path.join(os.path.expanduser("~"), ".dream-router"))
    ap.add_argument("--out", default="")
    a = ap.parse_args(argv)
    text = build(a.telemetry, a.router_home)
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
