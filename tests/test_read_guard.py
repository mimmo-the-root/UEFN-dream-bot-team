"""read_guard.py refuses a whole read of a big document, answers with its outline, and lets everything else through."""
import json, os, subprocess, sys, tempfile
H = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "project-template", "Claude", "hooks")
G = os.path.join(H, "read_guard.py")
ok = lambda c, m: (print(("PASS " if c else "FAIL ") + m), c or sys.exit(1))
def run(ti, env=None, raw=None):
    e = dict(os.environ); e.update(env or {})
    p = raw if raw is not None else json.dumps({"tool_input": ti})
    r = subprocess.run([sys.executable, G], input=p, capture_output=True, text=True, env=e)
    return r.returncode, (json.loads(r.stdout)["hookSpecificOutput"] if r.stdout.strip() else None)
d = tempfile.mkdtemp()
big = os.path.join(d, "BIG.md"); open(big, "w").write("# Title\n" + "".join("## Part %d\ntext line\n" % i + "x" * 80 + "\n" for i in range(900)))
small = os.path.join(d, "small.md"); open(small, "w").write("# s\nhello\n")
code = os.path.join(d, "big.verse"); open(code, "w").write("a" * 90000)
skill = os.path.join(d, "SKILL.md"); open(skill, "w").write("# x\n" + "b" * 90000)
js = os.path.join(d, "big.json"); json.dump({"alpha": list(range(5000)), "beta": "x" * 50000}, open(js, "w"))
rc, o = run({"file_path": big}); ok(o and o["permissionDecision"] == "deny" and "Part 7" in o["permissionDecisionReason"] and "offset" in o["permissionDecisionReason"], "a big markdown file is refused with its headings")
rc, o = run({"file_path": big, "limit": 50}); ok(o is None, "a read with a limit passes")
rc, o = run({"file_path": big, "offset": 120, "limit": 40}); ok(o is None, "a read with offset and limit passes")
rc, o = run({"file_path": small}); ok(o is None, "a small file passes")
rc, o = run({"file_path": code}); ok(o is None, "code files are never refused")
rc, o = run({"file_path": skill}); ok(o is None, "SKILL.md is never refused")
rc, o = run({"file_path": js}); ok(o and "alpha" in o["permissionDecisionReason"], "a big json file is refused with its keys")
rc, o = run({"file_path": os.path.join(d, "missing.md")}); ok(o is None, "a missing file passes")
rc, o = run({"file_path": big}, env={"UEFN_KIT_READ_GUARD": "0"}); ok(o is None, "UEFN_KIT_READ_GUARD=0 switches it off")
rc, o = run({"file_path": big}, env={"UEFN_KIT_READ_KB": "5000"}); ok(o is None, "UEFN_KIT_READ_KB raises the limit")
rc, o = run({}, raw="not json"); ok(rc == 0 and o is None, "bad input never blocks")
print("read guard tests OK")
