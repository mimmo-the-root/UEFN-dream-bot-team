"""lessons: add, dedupe, size cap, from-problems incremental, seed idempotent (temp vault and lab only)."""
import os, sys, json, tempfile, importlib.util
root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
spec = importlib.util.spec_from_file_location("lessons", os.path.join(root, "tools", "lessons.py"))
L = importlib.util.module_from_spec(spec); spec.loader.exec_module(L)
ok = lambda c, m: (print(("PASS " if c else "FAIL ") + m), c or sys.exit(1))

v = tempfile.mkdtemp(); lab = tempfile.mkdtemp()
hot = os.path.join(v, "wiki", "hot.md"); kit = os.path.join(v, "wiki", "kit", "lessons.md")
os.makedirs(os.path.dirname(hot)); open(hot, "w").write("# Hot\n\nintro\n\n## Other\nkeep me\n")
ok(L.add_lesson(v, "first rule", "t1"), "add returns True")
ok(L.add_lesson(v, "second rule", "t2"), "second add")
t = open(hot).read()
ok("## Lessons" in t and "keep me" in t and "## Other" in t, "section created, other content kept")
ok(t.index("second rule") < t.index("first rule"), "newest first")
ok(not L.add_lesson(v, "First   rule", "t3"), "duplicate refused")
ok(open(hot).read().count("first rule") == 1, "no duplicate in hot.md")
ok(open(kit).read().count("first rule") == 1, "kit/lessons.md has it once")
ok(len(L.make_line("x" * 500)) <= 200, "line max 200 chars")
for i in range(80):
    L.add_lesson(v, "bulk rule %d " % i + "y" * 150, "bulk")
ok(len(open(hot, "rb").read()) <= 6000, "hot.md under 6000 bytes")
t = open(hot).read()
ok("bulk rule 79" in t and "first rule" not in t and "keep me" in t, "oldest dropped, newest and other content kept")
ok("first rule" in open(kit).read(), "kit file keeps everything")

os.makedirs(os.path.join(lab, "plan"))
pf = os.path.join(lab, "plan", "PROBLEMS-FROM-COD.md")
open(pf, "w").write("time | task | what happened | fix | outcome\n--- | --- | --- | --- | ---\n2026-11-19 10:00 | T-1 | git blocked | planner does git | ok\n")
v2 = tempfile.mkdtemp()
ok(L.from_problems(lab, v2) == 1, "from-problems adds one")
ok(L.from_problems(lab, v2) == 0, "second run adds nothing")
open(pf, "a").write("2026-11-19 11:00 | T-2 | idle | loop with relay | ok\n")
ok(L.from_problems(lab, v2) == 1, "only the new line is done")
ok(json.load(open(os.path.join(lab, "logs", "lessons-state.json")))["last_line"] >= 4, "state remembered")
ok("2026-11-19 | T-2 |" in open(os.path.join(v2, "wiki", "hot.md")).read(), "date and source taken from row")

v3 = tempfile.mkdtemp()
ok(L.seed(v3) == len(L.SEED), "seed adds all")
a = open(os.path.join(v3, "wiki", "hot.md")).read()
ok(L.seed(v3) == 0 and open(os.path.join(v3, "wiki", "hot.md")).read() == a, "seed idempotent")
ok("learn-slicer" in a and "C:\\SecondBrainOssidian" in a, "seed content present")
