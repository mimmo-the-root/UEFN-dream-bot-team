#!/usr/bin/env python3
"""Fab product helper (v1.109). Lives in your profile (~/.claude/hooks), never inside a Fab project.

  python fab_pack.py check [project folder]          check the package against Epic's rules for an UEFN Source upload
  python fab_pack.py docs  [project folder] [--apply] create the Fab documents (dry run unless --apply); never overwrites
  python fab_pack.py zip   [project folder]          build <ProjectName>.zip next to the project, the way Fab wants it
  python fab_pack.py signature save <verse file>     keep the owner's signature block (ASCII art + links) from a finished file, in ~/.claude/fab-signature.txt
  python fab_pack.py signature show                  print the saved signature block
  python fab_pack.py header <Name> [project folder]  print the header for a new Verse file of a Fab product (layout + saved signature)
  python fab_pack.py grid  <images folder> [out.png] [--cols N] [--size WxH] [--bg #RRGGBB]   panoramic grid of images on a plain background (needs Pillow)

The project folder is the one that contains the .uefnproject file (or its Content folder). Fab wants the WHOLE project zipped, so the
generated files live inside Content, in the folder that holds the product's assets (Content/<Product>/): Documentation/ (setup and
usage for the customer) and FabListing/ (texts for the Fab portal). Documentation/SETTINGS.md is generated from the code (@editable
settings and the Summary of each Verse file); the other files are written once and then belong to you. `docs --apply` also moves
the folders an older version left next to Content into the new place. Use `--product NAME` when Content has more than one asset folder.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
MAX_PATH = 140
NAME_OK = re.compile(r"[A-Za-z0-9_]+")
FORBIDDEN_DIRS = ("Claude", ".claude", "Saved", "Intermediate")
FORBIDDEN_FILES = ("CLAUDE.md",)
VAGUE = {"assets", "newfolder", "new_folder", "folder", "untitled", "temp", "test", "misc", "stuff"}
UEFN_INTERNAL = {"__ExternalActors__", "__ExternalObjects__", ".git"}
THIRD_PARTY_DIRS = {"VerseUIKit": "Epic's Verse UI Kit: check its licence and declare it in the listing"}
GEN_MARK = "<!-- generated by fab_pack.py: edit the Verse code, not this file -->"


# ---- where the generated files live --------------------------------------------

NOT_PRODUCT = {"Collections", "Developers", "Claude"} | set(THIRD_PARTY_DIRS)


def product_folder(root, name=None):
    """Content/<Product>: the folder that holds the product's assets (most files; not Collections, Developers, Claude, a third-party
    library or UEFN's __External* folders). `name` forces one. Falls back to Content itself when there is none."""
    content = os.path.join(root, "Content")
    if name:
        return os.path.join(content, name)
    best, best_n = None, 0
    try:
        names = sorted(os.listdir(content))
    except OSError:
        return content
    for d in names:
        full = os.path.join(content, d)
        if not os.path.isdir(full) or d in NOT_PRODUCT or d.startswith("__"):
            continue
        n = sum(len(fs) for _b, _d, fs in os.walk(full))
        if n > best_n:
            best, best_n = full, n
    return best or content


def other_asset_folders(root, chosen):
    content = os.path.join(root, "Content")
    out = []
    try:
        for d in sorted(os.listdir(content)):
            full = os.path.join(content, d)
            if os.path.isdir(full) and d not in NOT_PRODUCT and not d.startswith("__") and os.path.abspath(full) != os.path.abspath(chosen) and any(fs for _b, _d, fs in os.walk(full)):
                out.append(d)
    except OSError:
        pass
    return out


def find_root(base):
    base = os.path.abspath(base)
    for cand in (base, os.path.dirname(base)):
        try:
            if any(n.endswith(".uefnproject") for n in os.listdir(cand)):
                return cand
        except OSError:
            pass
    return None


def check(root, product=None):
    """(blocks, warnings, notes) for the package rooted at `root`."""
    block, warn, notes = [], [], []
    top = os.path.basename(root.rstrip("/\\"))
    content = os.path.join(root, "Content")
    for n in FORBIDDEN_DIRS + FORBIDDEN_FILES:
        for where in (root, content):
            if os.path.exists(os.path.join(where, n)):
                block.append("%s is in the project (%s): a Fab package must not contain it" % (n, os.path.relpath(os.path.join(where, n), root).replace(os.sep, "/")))
    if os.path.isdir(os.path.join(root, ".lore")):
        warn.append(".lore (UEFN version-control data) is at the project root: check if your archive includes it; it is not content")
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in UEFN_INTERNAL and d not in FORBIDDEN_DIRS and d != ".lore"]
        for f in files:
            if f.endswith(".py"):
                block.append("%s: Python scripts are not allowed in an UEFN Source archive" % os.path.relpath(os.path.join(base, f), root).replace(os.sep, "/"))
    if os.path.isdir(content):
        for base, dirs, files in os.walk(content):
            dirs[:] = [d for d in dirs if d not in UEFN_INTERNAL and d not in FORBIDDEN_DIRS]
            for d in dirs:
                rel = os.path.relpath(os.path.join(base, d), content).replace(os.sep, "/")
                if not NAME_OK.fullmatch(d):
                    block.append("%s: folder name must use letters, digits and underscore only" % rel)
                try:
                    if not os.listdir(os.path.join(base, d)):
                        warn.append("%s: empty folder (remove it or fill it)" % rel)
                except OSError:
                    pass
                if d.lower() in VAGUE:
                    warn.append("%s: vague folder name (Fab asks for clear names, not %s)" % (rel, d))
                if d in THIRD_PARTY_DIRS and base == content:
                    warn.append("%s: third-party content: %s" % (d, THIRD_PARTY_DIRS[d]))
            for f in files:
                rel = os.path.relpath(os.path.join(base, f), content).replace(os.sep, "/")
                stem = os.path.splitext(f)[0]
                if f.endswith(".verse") and rel.split("/")[0] not in THIRD_PARTY_DIRS:
                    pr = header_problems(open(os.path.join(base, f), encoding="utf-8", errors="replace").read(), saved_signature())
                    if pr:
                        warn.append("%s: header needs work: %s" % (rel, "; ".join(p.replace("header has no ", "no ").replace("header does not carry", "missing") for p in pr)))
                if f.endswith((".uasset", ".umap", ".verse")) and not NAME_OK.fullmatch(stem):
                    block.append("%s: name must use letters, digits and underscore only" % rel)
                full = top + "/Content/" + rel
                if len(full) > MAX_PATH:
                    block.append("%s: path is %d characters as %s/Content/... in the archive (limit %d)" % (rel, len(full), top, MAX_PATH))
    else:
        block.append("no Content folder in %s" % root)
    if len(top) > 40:
        warn.append("project folder name %s is long: it counts in every path" % top)
    base = product_folder(root, product)
    brel = os.path.relpath(base, root).replace(os.sep, "/")
    for d in ("Documentation", "FabListing"):
        if os.path.isdir(os.path.join(root, d)):
            notes.append("%s/ is next to Content (older layout): Fab wants the whole project zipped and the generated files inside Content: run  fab_pack.py docs --apply  to move it into %s/" % (d, brel))
    for d, what in (("Documentation", "setup and usage for the customer"), ("FabListing", "texts for the Fab portal")):
        if not os.path.isdir(os.path.join(base, d)) and not os.path.isdir(os.path.join(root, d)):
            notes.append("no %s/%s yet (%s): run  fab_pack.py docs --apply" % (brel, d, what))
    more = other_asset_folders(root, base)
    if more:
        notes.append("Content has more than one asset folder (%s): the generated files go in %s; use --product NAME to choose another" % (", ".join(more), brel))
    lst = next((p for p in (os.path.join(base, "FabListing", "listing.md"), os.path.join(root, "FabListing", "listing.md")) if os.path.isfile(p)), "")
    if lst:
        m = re.search(r"^\s*Title:\s*(.+)$", open(lst, encoding="utf-8", errors="replace").read(), re.M)
        if m and "TODO" not in m.group(1) and len(m.group(1).strip()) > 30:
            warn.append("FabListing/listing.md: title is %d characters (about 30 or fewer is ideal)" % len(m.group(1).strip()))
        if re.search(r"TODO", open(lst, encoding="utf-8", errors="replace").read()):
            notes.append("FabListing/listing.md still has TODO fields")
    return block, warn, notes


# ---- code reading ---------------------------------------------------------

CLASS_RE = re.compile(r"^(\w+)(?:<[^>]*>)*\s*:=\s*(?:class|struct|interface|enum)\b")
DECL_RE = re.compile(r"^\s*(\w+)\s*:\s*([^=\n]+?)\s*(?:=\s*(.+?))?\s*$")


def summary(text):
    """The text after '# Summary:' in the header, continuation lines joined."""
    out, on = [], False
    for l in text.replace("\r\n", "\n").split("\n"):
        s = l.strip()
        if not s.startswith("#") and (s or out or on):
            break
        body = s.lstrip("#").strip()
        m = re.match(r"(?:Summary|WHAT IT DOES):?\s*(.*)", body)
        if m:
            on = True
            out.append(m.group(1))
        elif on and (re.match(r"[A-Z][A-Za-z ]+:\s", body) or re.fullmatch(r"[A-Z][A-Z ]{3,}", body)):
            break
        elif on and body:
            out.append(body)
    return " ".join(x for x in out if x)


def editables(text):
    """[{class, name, type, default, note}] for every @editable declaration."""
    res, cls, note = [], "", ""
    lines = text.replace("\r\n", "\n").split("\n")
    i = 0
    while i < len(lines):
        l = lines[i]
        m = CLASS_RE.match(l)
        if m:
            cls = m.group(1)
        s = l.strip()
        if s.startswith("#"):
            note = s.lstrip("#").strip()
            if not re.search(r"[A-Za-z]", note):
                note = ""
        elif s.startswith("@editable"):
            rest = re.sub(r"^@editable\s*(\([^)]*\)|\{[^}]*\})?\s*:?\s*", "", s)
            decl = rest
            if not decl:
                j = i + 1
                while j < len(lines) and (not lines[j].strip() or lines[j].strip().startswith("#")):
                    j += 1
                decl = lines[j].strip() if j < len(lines) else ""
                i = j
            d = DECL_RE.match(decl)
            if d:
                res.append({"class": cls, "name": d.group(1), "type": d.group(2).strip(), "default": (d.group(3) or "").strip(), "note": note})
            note = ""
        elif s:
            note = "" if not s.startswith("#") else note
        i += 1
    return res


def verse_files(root):
    out = []
    for base, dirs, files in os.walk(os.path.join(root, "Content")):
        dirs[:] = [d for d in dirs if d not in UEFN_INTERNAL and d not in FORBIDDEN_DIRS and d not in THIRD_PARTY_DIRS]
        out += [os.path.join(base, f) for f in sorted(files) if f.endswith(".verse")]
    return sorted(out)


def settings_md(root):
    name = os.path.basename(root.rstrip("/\\"))
    parts = [GEN_MARK, "", "# %s: settings" % name, "", "Every setting below appears in the Details panel of the device in UEFN. Defaults are the values in the code.", ""]
    for p in verse_files(root):
        t = open(p, encoding="utf-8", errors="replace").read()
        rel = os.path.relpath(p, os.path.join(root, "Content")).replace(os.sep, "/")
        ed, sm = editables(t), summary(t)
        if not ed and not sm:
            continue
        parts.append("## %s" % os.path.splitext(os.path.basename(p))[0])
        parts.append("")
        if sm:
            parts += [sm, ""]
        if ed:
            parts += ["| Setting | Type | Default | What it does |", "|---|---|---|---|"]
            for e in ed:
                parts.append("| `%s` | `%s` | %s | %s |" % (e["name"], e["type"].replace("|", "\\|"), ("`%s`" % e["default"].replace("|", "\\|")) if e["default"] else "set in the editor", e["note"].replace("|", "\\|")))
            parts.append("")
        parts.append("File: `%s`" % rel)
        parts.append("")
    return "\n".join(parts) + "\n"


def third_party_md(root):
    found = [d for d in THIRD_PARTY_DIRS if os.path.isdir(os.path.join(root, "Content", d))]
    rows = ["| What | Where | Licence | Declared |", "|---|---|---|---|"]
    for d in found:
        rows.append("| %s | Content/%s | TODO: check the licence | no |" % (d, d))
    if not found:
        rows.append("| (nothing detected) | | | |")
    return ("# Third-party software and assets\n\nFab asks you to declare everything in the product that you did not create. "
            "Add one row for every sourced asset, plugin or library.\n\n" + "\n".join(rows) + "\n")


def files_to_make(root):
    name = os.path.basename(root.rstrip("/\\"))
    return {
        "Documentation/README.md": "# %s\n\nTODO: one paragraph: what the product is and who it is for.\n\n## What is inside\n\nTODO: list the devices, widgets, materials and Verse files the customer receives.\n\n## Requirements\n\n- UEFN version: TODO\n- Other plugins or Epic libraries: TODO\n\n## Setup\n\n1. TODO: copy the content into your project.\n2. TODO: place the device in the level.\n3. TODO: set the options (see SETTINGS.md).\n\n## Usage\n\nTODO\n\n## Known limits\n\nTODO\n" % name,
        "FabListing/listing.md": "# Fab listing texts (copy them into the Fab portal)\n\nTitle: TODO (about 30 characters or fewer)\n\nShort description: TODO\n\n## Description\n\nTODO: what it does, what is included, how it is used. Declare third-party software and assets (see third_party.md).\n\n## Category and subcategories\n\nTODO\n\n## Tags\n\nTODO\n\n## Price\n\nTODO\n\n## Technical details\n\n- Supported UEFN version: TODO\n- Verse files: %d\n- LOD: TODO (yes or no)\n- Other: TODO\n" % len(verse_files(root)),
        "FabListing/third_party.md": third_party_md(root),
        "FabListing/screenshots.md": "# Images for the listing\n\nFab asks for a thumbnail that represents the product and a gallery; for packs, a panoramic grid on a plain background helps. Epic gives no image sizes, so check the current Fab pages before you make them.\n\n| File | What it shows | Done |\n|---|---|---|\n| thumbnail | the product in one picture | no |\n| gallery-1 | TODO | no |\n| gallery-2 | TODO | no |\n",
    }


def docs(root, apply, product=None):
    """Create the Fab documents inside Content/<Product>/ (dry run unless apply). Folders an older version left next to Content are
    moved in (files that do not exist there yet); nothing is overwritten or deleted. Returns (made, kept)."""
    base = product_folder(root, product)
    brel = os.path.relpath(base, root).replace(os.sep, "/")
    made, kept = [], []
    for d in ("Documentation", "FabListing"):
        old = os.path.join(root, d)
        if not os.path.isdir(old):
            continue
        for b2, _dirs, fs in os.walk(old):
            for f in fs:
                src = os.path.join(b2, f)
                rel = os.path.relpath(src, old).replace(os.sep, "/")
                rel = rel.replace("third-party.md", "third_party.md")  # a hyphen is not allowed in names inside the archive
                dst = os.path.join(base, d, *rel.split("/"))
                if os.path.exists(dst):
                    kept.append("%s/%s (also left next to Content: delete that copy)" % (d, rel))
                    continue
                made.append("moved %s/%s -> %s/%s/%s" % (d, rel, brel, d, rel))
                if apply:
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    os.replace(src, dst)
        if apply:
            for b2, _dirs, _fs in sorted(os.walk(old), key=lambda x: -len(x[0])):
                try:
                    os.rmdir(b2)
                except OSError:
                    pass
    gen = os.path.join(base, "Documentation", "SETTINGS.md")
    for rel, text in dict(files_to_make(root)).items():
        p = os.path.join(base, *rel.split("/"))
        if rel == "Documentation/SETTINGS.md":
            continue
        (kept if os.path.exists(p) else made).append("%s/%s" % (brel, rel))
        if apply and not os.path.exists(p):
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w", encoding="utf-8", newline="\n").write(text)
    regen = (not os.path.exists(gen)) or GEN_MARK in open(gen, encoding="utf-8", errors="replace").read()
    if regen:
        (made if not os.path.exists(gen) else kept).append("%s/Documentation/SETTINGS.md (generated)" % brel)
        if apply:
            os.makedirs(os.path.dirname(gen), exist_ok=True)
            open(gen, "w", encoding="utf-8", newline="\n").write(settings_md(root))
    else:
        kept.append("%s/Documentation/SETTINGS.md (yours: not regenerated)" % brel)
    return made, kept


def zip_package(root):
    """Write <ProjectName>.zip next to the project: the WHOLE project in one top folder, without .py, Saved, Intermediate and kit files.
    Refuses when other blocks remain (names, paths). Returns (path or None, problems)."""
    import time
    import zipfile
    top = os.path.basename(root.rstrip("/\\"))
    skip_dirs = set(FORBIDDEN_DIRS) | {".git"}
    files = []
    for base, dirs, fs in os.walk(root):
        dirs[:] = [d for d in dirs if d not in skip_dirs]
        for f in fs:
            if f.endswith(".py") or (base == root and f in FORBIDDEN_FILES) or f.endswith(".zip") and base == root:
                continue
            files.append(os.path.join(base, f))
    problems = []
    for p in files:
        rel = os.path.relpath(p, root).replace(os.sep, "/")
        if rel.startswith("Content/") and not rel.startswith(("Content/__External",)):
            parts = rel.split("/")
            for seg in parts[1:-1] + [os.path.splitext(parts[-1])[0]]:
                if not NAME_OK.fullmatch(seg):
                    problems.append("%s: name must use letters, digits and underscore only" % rel)
                    break
            if len(top + "/" + rel) > MAX_PATH:
                problems.append("%s: path is %d characters in the archive (limit %d)" % (rel, len(top + "/" + rel), MAX_PATH))
    if problems:
        return None, problems
    out = os.path.join(os.path.dirname(root.rstrip("/\\")), top + ".zip")
    if os.path.exists(out):
        out = os.path.join(os.path.dirname(out), "%s-%s.zip" % (top, time.strftime("%Y%m%d-%H%M%S")))
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files:
            z.write(p, top + "/" + os.path.relpath(p, root).replace(os.sep, "/"))
    return out, []


# ---- Verse header style for Fab products ------------------------------------

SIG_FILE = os.path.join(os.path.expanduser("~"), ".claude", "fab-signature.txt")
RULE = "# " + "-" * 90
HEADER_PARTS = ("WHAT IT DOES", "QUICK SETUP", "Author:")


def extract_signature(text):
    """The block from the '# Author:' line to the closing dashed rule of the header (ASCII art and links included)."""
    lines = text.replace("\r\n", "\n").split("\n")
    start = next((i for i, l in enumerate(lines) if re.match(r"#\s*Author:", l)), None)
    if start is None:
        return None
    end, seen = None, 0
    for i in range(start + 1, len(lines)):
        if not lines[i].startswith("#"):
            break
        if re.match(r"#\s*-{20,}\s*$", lines[i]):
            seen += 1
            end = i
            if seen == 2:
                break
    if end is None:
        return None
    return "\n".join(lines[start:end + 1]) + "\n"


def header_skeleton(name, signature=None):
    import time
    sig = signature or "# Author: TODO\n" + RULE + "\n"
    return "\n".join([
        "# %s.verse" % name, RULE,
        "# TODO Title  -  v1  (last modified: %s)" % time.strftime("%Y-%m-%d"), "#",
        "# WHAT IT DOES", "#   TODO: what the device does, in plain words.", "#",
        "# WHY IT IS USEFUL", "#   TODO: what the customer no longer has to do by hand.", "#",
        "# QUICK SETUP", "#   1. Place this device in your level.", "#   2. TODO: what to place or tag.",
        "#   3. TODO: the settings in the Details panel, one line each.", "#   4. Launch a session. Enable DebugLoggingEnabled to see the output in the Verse log.", "#",
        "# GOOD TO KNOW", "#   - TODO: limits and surprises.", "#"]) + "\n" + sig


def header_problems(text, signature=None):
    """Problems with the header of a Fab product's Verse file (all are warnings)."""
    head = []
    for l in text.replace("\r\n", "\n").split("\n"):
        if l.startswith("#") or not l.strip():
            head.append(l)
        else:
            break
    h = "\n".join(head)
    out = ["header has no '%s' part" % p.rstrip(":") for p in HEADER_PARTS if p not in h]
    if not re.search(r"\bv\d+(\.\d+)*\b.*last modified:\s*\d{4}-\d{2}-\d{2}", h):
        out.append("header has no 'vN (last modified: YYYY-MM-DD)' line")
    if signature:
        first = next((l for l in signature.splitlines() if "http" in l), None)
        if first and first.strip() not in h:
            out.append("header does not carry your saved signature block (fab_pack.py header <Name> prints it)")
    return out


def saved_signature():
    try:
        return open(SIG_FILE, encoding="utf-8").read()
    except OSError:
        return None


# ---- panoramic grid of images -------------------------------------------------

def make_grid(folder, out=None, cols=None, size=(1920, 1080), bg="#1a1a1a", gap=16):
    """Put the images of `folder` (png/jpg) in a grid on a plain background. Returns (path, count)."""
    try:
        from PIL import Image
    except ImportError:
        return None, "Pillow is not installed (pip install pillow)"
    exts = (".png", ".jpg", ".jpeg", ".webp")
    files = sorted(f for f in os.listdir(folder) if f.lower().endswith(exts) and not f.lower().startswith("grid"))
    if not files:
        return None, "no images in %s" % folder
    n = len(files)
    cols = cols or max(1, round((n * size[0] / size[1]) ** 0.5))
    rows = -(-n // cols)
    cw = (size[0] - gap * (cols + 1)) // cols
    ch = (size[1] - gap * (rows + 1)) // rows
    side = min(cw, ch)
    canvas = Image.new("RGB", size, bg)
    ox = (size[0] - (side * cols + gap * (cols - 1))) // 2
    oy = (size[1] - (side * rows + gap * (rows - 1))) // 2
    for i, f in enumerate(files):
        im = Image.open(os.path.join(folder, f)).convert("RGBA")
        w, h = im.size
        s = min(side / w, side / h)
        im = im.resize((max(1, int(w * s)), max(1, int(h * s))))
        x = ox + (i % cols) * (side + gap) + (side - im.size[0]) // 2
        y = oy + (i // cols) * (side + gap) + (side - im.size[1]) // 2
        canvas.paste(im, (x, y), im)
    out = out or os.path.join(folder, "grid.png")
    canvas.save(out)
    return out, n


def main(argv):
    if not argv or argv[0] not in ("check", "docs", "zip", "grid", "signature", "header"):
        print(__doc__)
        return 2
    if argv[0] == "signature":
        if len(argv) >= 3 and argv[1] == "save":
            sig = extract_signature(open(argv[2], encoding="utf-8", errors="replace").read())
            if not sig:
                print("no signature block found: expected a '# Author:' line followed by two dashed rules"); return 1
            os.makedirs(os.path.dirname(SIG_FILE), exist_ok=True)
            open(SIG_FILE, "w", encoding="utf-8", newline="\n").write(sig)
            print("saved to %s (%d lines):\n%s" % (SIG_FILE, len(sig.splitlines()), sig)); return 0
        if len(argv) >= 2 and argv[1] == "show":
            print(saved_signature() or "no signature saved yet: run  signature save <a finished verse file>"); return 0
        print(__doc__); return 2
    if argv[0] == "header":
        if len(argv) < 2:
            print(__doc__); return 2
        print(header_skeleton(argv[1], saved_signature()), end="")
        if not saved_signature():
            print("# (no signature saved: run  fab_pack.py signature save <a finished verse file>)")
        return 0
    if argv[0] == "grid":
        args = [a for a in argv[1:] if not a.startswith("--")]
        def opt(name, default):
            return argv[argv.index(name) + 1] if name in argv and argv.index(name) + 1 < len(argv) else default
        for v in (opt("--cols", ""), opt("--size", ""), opt("--bg", "")):
            if v in args:
                args.remove(v)
        if not args:
            print("usage: grid <images folder> [out.png]"); return 2
        size = tuple(int(x) for x in opt("--size", "1920x1080").lower().split("x"))
        out, n = make_grid(args[0], args[1] if len(args) > 1 else None, int(opt("--cols", 0)) or None, size, opt("--bg", "#1a1a1a"))
        print(("written: %s (%d images)" % (out, n)) if out else n)
        return 0 if out else 1
    product = argv[argv.index("--product") + 1] if "--product" in argv and argv.index("--product") + 1 < len(argv) else None
    pos = [a for a in argv[1:] if not a.startswith("--") and a != product]
    base = pos[0] if pos else os.getcwd()
    root = find_root(base)
    if not root:
        print("no UEFN project here (no .uefnproject file next to Content)")
        return 2
    if argv[0] == "check":
        b, w, n = check(root, product)
        for x in b:
            print("BLOCKS: " + x)
        for x in w:
            print("warning: " + x)
        for x in n:
            print("note: " + x)
        print("package check: %s" % ("%d problem(s) block the upload" % len(b) if b else "nothing blocks the upload") + ("; %d warning(s)" % len(w) if w else ""))
        return 1 if b else 0
    if argv[0] == "zip":
        out, problems = zip_package(root)
        for x in problems:
            print("BLOCKS: " + x)
        if out:
            print("written: %s (the whole project; no .py, Saved, Intermediate or kit files inside). Test it in a clean project before you upload." % out)
        return 0 if out else 1
    apply = "--apply" in argv
    made, kept = docs(root, apply, product)
    print(("created" if apply else "would create") + ": " + (", ".join(made) or "nothing"))
    print("left alone: " + (", ".join(kept) or "nothing"))
    if not apply and made:
        print("run again with --apply to write them")
    return 0


